async def getBybitServerTimeMS(session: aiohttp.ClientSession, server: str) -> int:
    """Get Bybit server time in milliseconds (async)."""
    url = server + "/v5/market/time"
    res = await _aio_get(session, url)
    if res and isinstance(res, dict) and "time" in res:
        return int(res["time"])
    # fallback to local time
    return int(datetime.now(timezone.utc).timestamp() * 1000)


async def getSymbolRules(signal) -> dict:
    """
    Fetch symbol trading rules from Bybit:
    - min_qty
    - max_qty
    - qty_step
    - max_trailing_stop (callback rate for trailing orders)
    """

    session = signal.get("session")
    symbol = signal.get("symbol")

    baseURL = signal.get("exchangeURL")
    endPoint = "/v5/market/instruments-info"
    url = baseURL + endPoint

    params = {"category": "linear", "symbol": symbol}

    async with session.get(url, params=params) as resp:
        data = await resp.json()

    if data.get("retCode") != 0:
        raise ValueError(f"Failed to fetch rules for {symbol}: {data}")

    info = data["result"]["list"][0]

    lot_size_filter = info.get("lotSizeFilter", {})
    min_qty = float(lot_size_filter.get("minOrderQty", 0.0))
    max_qty = float(lot_size_filter.get("maxOrderQty", 0.0))
    step = float(lot_size_filter.get("qtyStep", 0.0))

    # trailing filter might be nested differently or missing
    trailing_filter = info.get("trailingStop", {}) or info.get("trailingStopFilter", {})
    max_trailing = float(
        trailing_filter.get("maxTrailingActive", 0.2)
    )  # fallback = 0.2

    return {
        "min_qty": min_qty,
        "max_qty": max_qty,
        "step": step,
        "max_trailing": max_trailing,
    }


