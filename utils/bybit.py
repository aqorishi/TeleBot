async def getPositionQty(signal):
    """
    Get current open position quantity for a given symbol from Bybit.
    Returns float qty or None if no position is found.
    """
    session = signal.get("session")

    baseURL = signal.get("exchangeURL")
    endPoint = "/v5/position/list"
    url = baseURL + endPoint

    api_key, api_secret = getSecretsFromSignal(signal)
    symbol = signal.get("symbol")

    payload = {
        "api_key": api_key,
        "symbol": symbol,
        "category": "linear",
        "timestamp": await getBybitServerTimeMS(session, baseURL),
        "recv_window": 20000,
    }

    # Sign request
    payload["sign"] = signRequest(payload, api_secret)

    res = await _aio_get(session, url, params=payload)

    if not res or res.get("retCode") != 0:
        return None

    positions = res.get("result", {}).get("list", [])
    if not positions:
        return None

    # Extract size of the first matching position
    qty = positions[0].get("size")
    return float(qty) if qty else None


