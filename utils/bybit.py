async def getPosition(signal: dict) -> Optional[dict]:
    """
    ✅ Get open position for a symbol (Bybit v5)
    Uses the shared aiohttp session passed as argument.
    """
    session = signal.get("session")
    api_key, api_secret = getSecretsFromSignal(signal)
    symbol = signal.get("symbol")

    baseURL = signal.get("exchangeURL")
    endPoint = "/v5/position/list"
    url = baseURL + endPoint

    # گرفتن زمان سرور با همان session
    timestamp = await getBybitServerTimeMS(session, baseURL)
    if not timestamp:
        await adminReport("⚠️ getBybitServerTimeMS returned None!")
        return None

    # پارامترهای لازم برای امضا
    params = {
        "api_key": api_key,
        "category": "linear",
        "symbol": symbol.upper(),
        "timestamp": timestamp,
        "recv_window": "5000",
    }

    # ساخت امضا
    signature = signRequest(params, api_secret)
    params["sign"] = signature

    try:
        async with session.get(url, params=params) as resp:
            try:
                data = await resp.json()
            except Exception:
                text = await resp.text()
                await adminReport(f"⚠️ Invalid JSON response: {text}")
                return None

            if not isinstance(data, dict):
                await adminReport(f"⚠️ Unexpected data type: {type(data)} -> {data}")
                return None

            if data.get("retCode") != 0:
                await adminReport(
                    f"⚠️ Bybit error {data.get('retCode')}: {data.get('retMsg')}"
                )
                await adminReport(f"🔍 URL: {resp.url}")
                return None

            positions = data.get("result", {}).get("list", [])
            if not positions:
                await adminReport(f"ℹ️ No open positions found for {symbol}")
                return None

            for pos in positions:
                if (
                    pos.get("symbol") == symbol.upper()
                    and float(pos.get("size", 0)) != 0
                ):
                    return pos

            # await adminReport(
            #     f"ℹ️ Position list exists but no active position found for {symbol}"
            # )
            return None

    except Exception as e:
        await adminReport(f"ByBit:  : {ln()} ❌ getPosition error for {symbol}: {e}")
        return None


