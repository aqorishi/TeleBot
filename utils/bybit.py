def signRequest(params: dict, api_secret: str) -> str:
    """Generate Bybit v5 signature."""
    # Convert all values to string (Booleans -> 'true'/'false')
    param_str_dict = {
        k: str(v).lower() if isinstance(v, bool) else str(v) for k, v in params.items()
    }
    # Sort params alphabetically by key
    param_str = "&".join([f"{k}={v}" for k, v in sorted(param_str_dict.items())])
    # Generate HMAC SHA256
    return hmac.new(
        api_secret.encode("utf-8"), param_str.encode("utf-8"), hashlib.sha256
    ).hexdigest()


