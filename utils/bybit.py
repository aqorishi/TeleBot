def floorToStepDec(value, step) -> Decimal:
    value = Decimal(str(value))
    step = Decimal(str(step))

    if step == 0:
        return value

    units = (value / step).to_integral_value(rounding=ROUND_DOWN)
    return units * step


def ceilUnits(q: Decimal, step: Decimal) -> int:
    if step == 0:
        return 0
    units = (q / step).to_integral_value(rounding=ROUND_DOWN)
    if units * step < q:
        units = units + 1
    return int(units)


async def saveTradeSnapshot(placedOrders: list):
    """
    Save trade snapshot (State Machine ready).
    """

    savePath = "./logs/trades.json"
    os.makedirs(os.path.dirname(savePath), exist_ok=True)

    
    # Load existing file
    if os.path.exists(savePath):
        try:
            with open(savePath, "r", encoding="utf-8") as f:
                allTrades = json.load(f)
        except Exception:
            allTrades = {}
    else:
        allTrades = {}

    if not placedOrders:
        raise ValueError("placedOrders is empty")

    mainOrder = next(
        (o for o in placedOrders if o["variant"] == "main"),
        None,
    )

    if not mainOrder:
        raise ValueError("Main order not found")

    symbol = mainOrder["symbol"]

    entries = []
    totalQty = 0.0
    
    # Build entries
    for order in placedOrders:

        qty = float(order.get("qty") or 0)
        price = float(order.get("price") or 0)

        totalQty += qty

        entries.append(
            {
                "variant": order["variant"],
                "price": price,
                "qty": qty,

                "orderId": order["order_id"],

                # updated by syncTradeState()
                "filled": False,
                "cancelled": False,

                "fillPrice": None,
                "fillQty": 0.0,
            }
        )

    # Qty
    step = float(mainOrder["step"])
    totalQty = float(floorToStepDec(totalQty, step))
    
    # Take Profits
    takeProfits = [
        float(tp)
        for tp in (mainOrder.get("takeProfits") or [])
    ]
    
    if mainOrder["side"].lower() == "buy":
        takeProfits.sort()
    else:
        takeProfits.sort(reverse=True)

    tpOrders = []

    for i, tp in enumerate(takeProfits):
        tpOrders.append(
            {
                "index": i,

                "price": tp,

                # later generated by allocate_tp_qtys()
                "qty": None,

                "orderId": None,

                "placed": False,
                "filled": False,
                "cancelled": False,
            }
        )

    stopLoss = float(mainOrder.get("stopLoss") or 0)

    tradeSummary = {

        # Identification
        "symbol": symbol,
        "source": mainOrder["source"],

        "side": mainOrder["side"],

        "state": "waiting_entry",

        # Exchange info
        "category": mainOrder["category"],
        "marginMode": mainOrder["margin_mode"],
        "leverage": mainOrder["leverage"],

        # Instrument limits
        "minQty": float(mainOrder["minQty"]),
        "maxQty": float(mainOrder["maxQty"]),
        "step": float(mainOrder["step"]),
        "maxTrailing": float(mainOrder["maxTrailing"]),

        # Planned Trade
        "entry": float(mainOrder["price"]),

        "qty": totalQty,

        "entries": entries,

        # Current Position
        "position": {
            "opened": False,
            "qty": 0.0,
            "avgPrice": None,
            "side": None,
        },

        # Stop Loss
        "SLPrice": stopLoss,
        "SLNow": stopLoss,

        "slOrderId": None,

        # Take Profits
        "tpIndexHit": 0,

        "tpOrders": tpOrders,

        # Metadata
        "createdAt": datetime.now(timezone.utc).isoformat(),

        "updatedAt": datetime.now(timezone.utc).isoformat(),
    }

    allTrades[symbol] = tradeSummary
    
    await adminReport(f"All trades for save is: \n{allTrades}")

    with open(savePath, "w", encoding="utf-8") as f:
        json.dump(
            allTrades,
            f,
            indent=2,
            ensure_ascii=False,
        )

    await adminReport(f"✅ Trade {symbol} saved.")

    return tradeSummary


async def _aio_get(
    session: aiohttp.ClientSession,
    server: str,
    params: dict = None,
    headers: dict = None,
):
    try:
        async with session.get(
            server, params=params, headers=headers, timeout=20
        ) as resp:
            text = await resp.text()
            try:
                return json.loads(text)
            except Exception:
                await adminReport(f"⚠️ Non-JSON response from {server}: {text}")
                return None
    except Exception as e:
        await adminReport(f"❌ HTTP GET failed {server}: {e}")
        return None


