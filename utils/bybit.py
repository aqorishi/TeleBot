async def getUSDTBalance(signal: dict) -> float:
    """Fetch USDT unified wallet available balance (async)."""
    # await adminReport(f"Signal from getUSDTBalance \n {signal}")
    try:
        session = signal.get("session")

        baseURL = signal.get("exchangeURL")
        endPoint = "/v5/account/wallet-balance"
        url = baseURL + endPoint

        recv_window = 20000
        timestamp = await getBybitServerTimeMS(session, baseURL)

        api_key, api_secret = getSecretsFromSignal(signal)
        if not api_key or not api_secret:
            await adminReport("❌ No API key/secret provided for balance call")
            return 0.0

        params = {"accountType": "UNIFIED"}
        query_string = "accountType=UNIFIED"

        origin_string = str(timestamp) + api_key + str(recv_window) + query_string
        signature = hmac.new(
            api_secret.encode("utf-8"), origin_string.encode("utf-8"), hashlib.sha256
        ).hexdigest()

        headers = {
            "X-BAPI-API-KEY": api_key,
            "X-BAPI-SIGN": signature,
            "X-BAPI-TIMESTAMP": str(timestamp),
            "X-BAPI-RECV-WINDOW": str(recv_window),
        }

        balance_response = await _aio_get(session, url, params=params, headers=headers)
        balance_data = balance_response["result"]["list"][0]["coin"]

        usdt_balance = next(
            (item["walletBalance"] for item in balance_data if item["coin"] == "USDT"),
            None,
        )
        # await adminReport(f"💰 Balance response: {balance_response}")

        balance = float(usdt_balance) if usdt_balance is not None else 0.0
        return balance

    except Exception as e:
        await adminReport(f"❌ Error getting USDT balance: {e}")
        return 0.0


async def getQtyFromUSD(signal, usd_amount: float) -> str:
    """
    Convert USD amount to base qty using current price, step, and min_qty.
    Uses Decimal for precision and rounds based on trade side:
        - 'buy'  => ROUND_DOWN  (avoid overspending)
        - 'sell' => ROUND_UP    (ensure full closure)
    Returns formatted qty as string (e.g. '0.008', '1.000').
    """
    session = signal.get("session")
    symbol = signal.get("symbol")
    baseURL = signal.get("exchangeURL")
    side = str(signal.get("side", "buy")).lower()  # default buy if missing

    try:
        price = await getCurrentPrice(signal)
        if not price or price <= 0:
            await adminReport(
                f"❌ Invalid price for {symbol} when calculating qty (price={price})"
            )
            return "0.00"

        # تبدیل به Decimal برای دقت بالا
        usd_amount_d = Decimal(str(usd_amount))
        price_d = Decimal(str(price))
        step_d = Decimal(str(signal.get("step", "0.001")))
        min_qty_d = Decimal(str(signal.get("minQty", "0.001")))

        # --- محاسبه مقدار خام ---
        raw_qty = usd_amount_d / price_d

        # انتخاب نوع گرد کردن بر اساس نوع معامله
        rounding_mode = ROUND_DOWN if side == "buy" else ROUND_UP

        # محاسبه گام‌ها و مقدار نهایی
        steps = (raw_qty / step_d).to_integral_value(rounding=rounding_mode)
        adjusted_qty = steps * step_d

        # اطمینان از رعایت حداقل مقدار
        if adjusted_qty < min_qty_d:
            adjusted_qty = min_qty_d
            await adminReport(
                f"⚠️ {symbol}: Adjusted qty below min_qty, set to {min_qty_d}"
            )

        # تعیین تعداد اعشار بر اساس step
        decimals = abs(int(math.log10(float(step_d)))) if step_d < 1 else 0
        qty_formatted = f"{adjusted_qty:.{decimals}f}"

        # await adminReport(
        #     f"🧮 {symbol} | {side.upper()} | usd={usd_amount_d} | price={price_d} | "
        #     f"min_qty={min_qty_d} | step={step_d} | adjusted={adjusted_qty} | "
        #     f"qty_formatted={qty_formatted}"
        # )

        return qty_formatted

    except Exception as e:
        await adminReport(f"❌ Error in getQtyFromUSD for {symbol}: {e}")
        return "0.00"


