async def allocateUSDToEntries(
    signal: dict,
    clean_entries: list,
    base_ratio: Decimal = Decimal("0.5"),  # entry اول نصف دومی
):
    total_usd = Decimal(str(signal.get("qty") or "0"))
    side_raw = signal.get("side", "").lower()
    is_long = side_raw in ("buy", "long")

    entries = [Decimal(str(e)) for e in clean_entries]
    if len(entries) != 2:
        raise ValueError("This strategy supports exactly 2 entries")

    P1, P2 = entries

    distance = abs(P1 - P2)
    ref_price = max(P1, P2)

    # ضریب فاصله (هرچه فاصله بیشتر → وزن بیشتر)
    distance_factor = Decimal("1") + (distance / ref_price)

    if is_long:
        w1 = base_ratio
        w2 = Decimal("1") * distance_factor
    else:  # SELL
        w1 = Decimal("1") * distance_factor
        w2 = base_ratio

    sum_w = w1 + w2

    A1 = (total_usd * w1 / sum_w).quantize(Decimal("0.01"), rounding=ROUND_DOWN)
    A2 = total_usd - A1

    return [A1, A2]


