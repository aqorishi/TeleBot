def generateRatioList(n):
    values = [1 / (i + 1) for i in range(n)]
    total = sum(values)
    normalized = [round(v / total, 2) for v in values]

    # For ensuring sum to 1.0 after rounding
    diff = 1 - sum(normalized)
    normalized[0] += diff  # Adjust the first element to fix rounding error
    return normalized


def splitQtyByWeights(total_qty, weights, min_qty, step=None) -> List[float]:
    """
    Split total_qty into parts according to weights, ensuring:
    - each part is a multiple of `step` (or min_qty if step not given)
    - total sum never exceeds total_qty
    - leftover from rounding is added to first part
    Returns a list of float numbers.
    """
    total_qty = Decimal(str(total_qty))
    min_qty = Decimal(str(min_qty))
    step = Decimal(str(step or min_qty))

    if min_qty <= 0:
        raise ValueError("min_qty must be > 0")
    if total_qty <= 0:
        return [0.0] * len(weights)

    weights_d = [Decimal(str(w)) for w in weights]
    total_weight = sum(weights_d)
    if total_weight <= 0:
        raise ValueError("sum of weights must be > 0")

    # کل واحدها بر حسب step
    total_units = int((total_qty / step).to_integral_value(rounding=ROUND_FLOOR))
    if total_units == 0:
        return [0.0] * len(weights)

    # تقسیم وزن‌ها
    raw_units = [(w * Decimal(total_units) / total_weight) for w in weights_d]
    int_units = [int(u.to_integral_value(rounding=ROUND_FLOOR)) for u in raw_units]

    allocated = sum(int_units)
    remainder_units = total_units - allocated

    # اضافه کردن باقی‌مانده به اولین بخش
    if remainder_units > 0:
        int_units[0] += remainder_units

    # تبدیل واحدها به مقدار qty واقعی
    parts = [float(Decimal(u) * step) for u in int_units]

    # اطمینان از اینکه هیچ مقداری کمتر از min_qty نیست
    parts = [p if p >= float(min_qty) else float(min_qty) for p in parts]

    return parts


async def createTPOrders(signal) -> List[dict]:
    """
    Create Take-Profit orders based on pre-calculated weights and total position qty.
    Uses splitQtyByWeights_decimal() to ensure valid qty distribution.
    """

    keys = signal.get("keys", {})
    symbol = signal.get("symbol")
    side = signal.get("side")
    takeProfits = signal.get("takeProfits", [])
    max_trailing = signal.get("maxTrailing")
    tp_orders = []
    n = len(takeProfits)
    total_qty = await getPositionQty(signal)
    min_qty = Decimal(str(signal.get("minQty", "0.001")))
    weights = generateRatioList(n)

    # ✅ split total qty according to weights (ensures correct rounding)
    splitted_qty = splitQtyByWeights(total_qty, weights, min_qty)

    await adminReport(f"⚖️ Split total qty={total_qty} into {splitted_qty}")

    # loop through TP levels
    for idx, (tp_price, qty) in enumerate(zip(takeProfits, splitted_qty)):
        tp_price = Decimal(str(tp_price))
        qty = Decimal(str(qty))

        if qty <= 0:
            continue

        await adminReport(
            f"TP{idx+1}: price={tp_price}, qty={qty}, weight={weights[idx]}"
        )

        order = copy.deepcopy(signal_template)
        order.update(
            {
                "session": signal.get("session"),
                "demo": signal.get("demo"),
                "exchangeURL": signal.get("exchangeURL"),
                "keys": keys,
                "variant": f"TP{idx+1}",
                "symbol": symbol,
                "side": "Sell" if side == "Buy" else "Buy",
                "orderType": "Limit",
                "qty": str(qty),
                "price": str(tp_price),
                "reduceOnly": True,
            }
        )

        # ✅ last TP: enable trailing stop or close on trigger
        if idx == n - 1:
            order["closeOnTrigger"] = True
            order["trailingStop"] = float(max_trailing or 0.2)

        # remove None values
        order = {k: v for k, v in order.items() if v is not None}
        tp_orders.append(order)

    # ✅ Ensure total qty matches exactly total_qty
    total_alloc = sum(Decimal(o["qty"]) for o in tp_orders)
    diff = Decimal(str(total_qty)) - total_alloc
    if diff != 0 and tp_orders:
        tp_orders[0]["qty"] = str(
            (Decimal(tp_orders[0]["qty"]) + diff).quantize(Decimal(str(min_qty)))
        )
        await adminReport(f"Adjusted first TP qty by {diff} to fix rounding.")

    # await adminReport(f"✅ Created {len(tp_orders)} TP orders for {symbol}:\n{tp_orders}")

    return tp_orders


async def placeSignalOrder(signal: dict) -> dict:
    """
    Place an order on Bybit directly from the given signal
    without modifying the input signal in any way.
    """
    # await adminReport(f"Placing order for signal:\n {signal}")
    
    session = signal.get("session")

    baseURL = signal.get("exchangeURL")
    endPoint = "/v5/order/create"
    url = baseURL + endPoint

    api_key, api_secret = getSecretsFromSignal(signal)
    if not api_key or not api_secret:
        await adminReport("❌ Missing API keys in signal")
        return None

    variant = signal.get("variant")
    if not variant:
        await adminReport("❌ Missing variant in signal")
        return None

    symbol = signal.get("symbol")
    if not symbol:
        await adminReport("❌ Missing symbol in signal")
        return None

    qty = signal.get("qty")
    if not qty:
        await adminReport(f"⚠️ No qty defined for {symbol}, skipping order.")
        return None

    order_type = signal.get("orderType", "Limit")
    entry_price = signal.get("price")  # None for Market orders

    payload = {
        "api_key": api_key,
        "symbol": symbol,
        "side": signal.get("side"),
        "qty": qty,
        "price": entry_price,
        "orderType": order_type,
        "category": signal.get("category", "linear"),
        "timeInForce": signal.get("timeInForce", "GTC"),
        "reduceOnly": signal.get("reduceOnly", False),
        "closeOnTrigger": signal.get("closeOnTrigger", False),
        "marginMode": signal.get("margin_mode", "isolated"),
        "timestamp": await getBybitServerTimeMS(session, baseURL),
        "recv_window": 20000,
    }
    
    # if stopLossFlag:
    #     payload["stopLoss"] = signal.get("stopLoss")

    # Cleanup None values
    payload = {k: v for k, v in payload.items() if v is not None}

    # Sign
    payload["sign"] = signRequest(payload, api_secret)

    # Send request
    res = await _aio_post(session, url, payload)

    if not res or res.get("retCode") != 0:
        await adminReport(f"❌ Order failed for {symbol}: {res}")
        return None

    order_id = res.get("result", {}).get("orderId")
    placed_time = res.get("time") or await getBybitServerTimeMS(session, baseURL)


    return {
        "response": res.get("retCode"),
        "order_id": order_id,
        "price": entry_price,
        "qty": str(qty),
        "time": placed_time,
        "status": "placed",
    }


