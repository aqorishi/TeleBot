                    # await adminReport(f"Ordered Position is:\n{executedOrders}" if executedOrders else f"No Ordered Position")

                    if executedPosition:
                        mainSignal["execPrice"] = executedPosition.get(
                            "avgPrice", 0.0
                        )
                        mainSignal["status"] = "placed"

                    placedOrders.append(mainSignal)

                    # Place alt signals
                    for altSig in altSignals:
                        order = await placeSignalOrder(altSig)
                        if order and order.get("response") == 0:
                            altSig["order_id"] = order["order_id"]
                            altSig["order_timestamp"] = order["time"]
                            altSig["status"] = "ordered"

                            executedPosition = await getPosition(altSig)
                            # executed_orders = await getOpenOrders(signal)

